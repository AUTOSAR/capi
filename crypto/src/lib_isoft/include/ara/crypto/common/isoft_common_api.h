/// @brief Save data to a file
/// @param fileName The name of the file receiving the data
/// @param pData Data: starting address of the memory
/// @param nDataLen Data length
/// @return true if save to file sucess false otherwise
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00115
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline bool SaveDataToFile(ara::core::StringView const &fileName,
                           uint8_t const *const pData,
                           uint32_t const nDataLen) noexcept
{
    if (fileName.empty()) {
        ara::crypto::isoft_def::LogInfo() << "SaveDataToFile : Do Noing";
        return true;
    }
    nai_int_t const naiOpenMode{static_cast< nai_int_t >(kInt_64 | kInt_2)};  //NAI_O_CREAT | NAI_O_RDWR
    nai_fd_t const fd{nai_file_open(fileName.data(), naiOpenMode, static_cast< size_t >(kInt_666U))};
    if (static_cast< nai_fd_t >(-1) == fd) {
        ara::crypto::isoft_def::LogInfo() << "SaveDataToFile :" << fileName.data() << " Not Exist\n";
        return true;
    }
    intptr_t r{nai_file_write(fd, pData, static_cast< size_t >(nDataLen))};
    if (r != static_cast< intptr_t >(nDataLen)) {
        return false;
    }
    r = nai_file_close(fd);
    return r >= 0;
}
