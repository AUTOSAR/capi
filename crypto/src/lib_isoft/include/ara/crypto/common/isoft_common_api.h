/// @brief uuid
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00116
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
struct P_Uuid
{
    /// @brief nTimeLow
    uint32_t nTimeLow;
    /// @brief nTimeMid
    uint16_t nTimeMid;
    /// @brief nTimeHighAndVersion
    uint16_t nTimeHighAndVersion;
    /// @brief nClockSeqAndReserved
    uint8_t nClockSeqAndReserved;
    /// @brief nClockSeqLow
    uint8_t nClockSeqLow;
    /// @brief node
    uint8_t node[kInt_6U];
};
/// @brief Return a UUID generated by time
/// @return UUID instance
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00117
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline Uuid GetUuidByTime() noexcept
{
    std::time_t const t0{std::chrono::system_clock::to_time_t(std::chrono::system_clock::now())};
    std::tm const *const tm0{std::localtime(&t0)};  // NOLINT
    P_Uuid uid{kInt_0U, kInt_0U, kInt_0U, kInt_0U, kInt_0U, {kInt_0U}};
    Uuid uidData;
    uid.nTimeLow             = static_cast< uint32_t >(tm0->tm_year) + kInt_1900U;
    uid.nTimeMid             = static_cast< uint16_t >(tm0->tm_mon);
    uid.nTimeHighAndVersion  = static_cast< uint16_t >(tm0->tm_mday);
    uid.nClockSeqAndReserved = 0U;
    uid.nClockSeqLow         = static_cast< uint8_t >(tm0->tm_sec);

    std::mt19937 gen{static_cast< uint_fast32_t >(tm0->tm_sec)};  // Mersenne Twister generator
    std::uniform_int_distribution<> dis{0, kInt_255};             // Define distribution range

    for (uint8_t &itData : uid.node) {
        itData      = static_cast< uint8_t >(dis(gen));
        std::ignore = gen;
    }
    std::ignore = memcpy(static_cast< uint64_t * >(static_cast< void * >(&uidData)),
                         static_cast< uint64_t * >(static_cast< void * >(&uid)), sizeof(uid));
    return uidData;
}
