/// @brief Determine if b == (a & b)
/// @param a T template object
/// @param b T template object
/// @return true if b == (a & b) false otherwise
/// @code{.isoft}
/// @tparam T
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00130
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
template < typename T >
inline bool T_IsAndData(T const a, T const b) noexcept
{
    uint32_t const nA{static_cast< uint32_t >(a)};
    uint32_t const nB{static_cast< uint32_t >(b)};
    return nB == (nA & nB);
}
