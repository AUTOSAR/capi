/// @brief Number => Base16 character
/// @param n Integer data
/// @return String
/// @code{.isoft}
/// @tparam T
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00123
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
template < typename T >
inline ara::crypto::char8_t T_itochar(T n) noexcept
{
    n = n % static_cast< T >(kInt_0x10);
    if (n >= static_cast< T >(kInt_10)) {
        return static_cast< ara::crypto::char8_t >(static_cast< T >(kChar_a) + (n - static_cast< T >(kInt_10)));
    }
    return static_cast< ara::crypto::char8_t >(static_cast< T >(kChar_0) + n);
}
/// @brief Base16 character => number
/// @param ch Input character
/// @return Integer
/// @code{.isoft}
/// @tparam T
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00124
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
template < typename T >
inline T T_chartoi(ara::crypto::char8_t const ch) noexcept
{
    T nData;
    if ((ch >= kChar_A) && (ch <= kChar_Z)) {
        nData = static_cast< T >(ch) - static_cast< T >(kChar_A) + static_cast< T >(kInt_10);
    } else if ((ch >= kChar_a) && (ch <= kChar_z)) {
        nData = static_cast< T >(ch) - static_cast< T >(kChar_a) + static_cast< T >(kInt_10);
    } else if ((ch >= kChar_0) && (ch <= kChar_9)) {
        nData = static_cast< T >(ch) - static_cast< T >(kChar_0);
    } else {
        nData = static_cast< T >(0);
    }
    return nData;
}
