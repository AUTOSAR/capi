/// @brief String increment  simple processing
/// @param counter Counter
/// @param len Length
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00170
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline void Ctr_inc(uint8_t *const counter, uint32_t const len) noexcept
{
    size_t n{len};
    size_t c{1U};

    while (n > 0U) {
        --n;
        c += *(counter + n);
        *(counter + n) = static_cast< uint8_t >(c);
        c >>= kInt_8U;
    }
}
/// @brief String decrement  simple processing
/// @param counter Counter
/// @param len Length
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00171
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline void Ctr_dec(uint8_t *const counter, uint32_t const len) noexcept
{
    size_t n{len};
    size_t const c{1U};

    while (n > 0U) {
        --n;
        if (*(counter + n) < c) {
            continue;
        }
        *(counter + n) -= c;
        break;
    }
}
