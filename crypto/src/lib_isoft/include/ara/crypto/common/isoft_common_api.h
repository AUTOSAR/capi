/// @brief Return the ceiling of integer A divided by B
/// @param a Similar to dividend in division
/// @param b Similar to divisor in division
/// @return The ceiling of A divided by B
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00132
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline uint32_t T_AlignNumberUp(uint32_t const a, uint32_t const b) noexcept
{
    uint32_t const bStep{b - 1U};
    return (a + bStep) & (~bStep);
}
/// @brief Return the ceiling of integer A divided by B
/// @param a Similar to dividend in division
/// @param b Similar to divisor in division
/// @return The ceiling of A divided by B
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00133
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline int64_t T_AlignNumberUp(int64_t const a, uint32_t const b) noexcept
{
    uint64_t const bStep{b - static_cast< uint64_t >(1)};
    uint64_t nA{static_cast< uint64_t >(a) + bStep};
    nA = nA & (~bStep);
    return static_cast< int64_t >(nA);
}
/// @brief Return the floor of integer A divided by B
/// @param a Similar to dividend in division
/// @param b Similar to divisor in division
/// @return The floor of A divided by B
/// @code{.isoft}
/// @interface_level=unit
/// @trace_id_ad=AD_CRYPTO_02548
/// @trace_id_dd=DD_CRYPTO_00134
/// @trace_id_sr=SR_CRYPTO_06005
/// @needwork = dd
/// @endcode
inline int64_t T_AlignNumberDown(int64_t const a, uint32_t const b) noexcept
{
    uint64_t const bStep{b - static_cast< uint64_t >(1)};
    uint64_t nA{static_cast< uint64_t >(a)};
    nA = nA & (~bStep);
    return static_cast< int64_t >(nA);
}
